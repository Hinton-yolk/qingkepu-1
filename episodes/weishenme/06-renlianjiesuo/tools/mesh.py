#!/usr/bin/env python3
"""Build assets/mesh/face.js from MediaPipe's canonical face model (Apache-2.0, google-ai-edge/mediapipe,
mediapipe/modules/face_geometry/data/canonical_face_model.obj): Loop-subdivide it twice, then attach per-vertex
weights for the regions the film paints (lips, blush, eyeshadow, the contour on the nose sides, the eye ring), and
build the mask (a smooth fabric surface over the lower face) as its own mesh.
Units: cm; x to the face's left (viewer's right), y up, z towards the viewer; the nose tip is at z ≈ 7.6."""
import json, pathlib
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
V, F = [], []
for l in open(ROOT / "assets/mesh/canonical_face_model.obj"):
    p = l.split()
    if not p: continue
    if p[0] == "v": V.append([float(x) for x in p[1:4]])
    if p[0] == "f": F.append([int(x.split("/")[0]) - 1 for x in p[1:4]])
V = np.array(V); F = np.array(F)


def loop(V, F):
    edges = {}
    def ekey(a, b): return (a, b) if a < b else (b, a)
    opp = {}
    for f in F:
        for i in range(3):
            a, b, c = f[i], f[(i + 1) % 3], f[(i + 2) % 3]
            opp.setdefault(ekey(a, b), []).append(c)
    nv = len(V); newV = []; eidx = {}
    for (a, b), cs in opp.items():
        if len(cs) == 2: p = 3 / 8 * (V[a] + V[b]) + 1 / 8 * (V[cs[0]] + V[cs[1]])
        else: p = 0.5 * (V[a] + V[b])
        eidx[(a, b)] = nv + len(newV); newV.append(p)
    # move the old vertices
    nb = [set() for _ in range(nv)]; bnb = [set() for _ in range(nv)]
    for (a, b), cs in opp.items():
        nb[a].add(b); nb[b].add(a)
        if len(cs) == 1: bnb[a].add(b); bnb[b].add(a)
    oldV = np.zeros_like(V)
    for i in range(nv):
        if bnb[i]:
            q = list(bnb[i]); oldV[i] = 0.75 * V[i] + 0.125 * (V[q[0]] + V[q[-1]])
        else:
            n = len(nb[i]); beta = (5 / 8 - (3 / 8 + 0.25 * np.cos(2 * np.pi / n)) ** 2) / n
            oldV[i] = (1 - n * beta) * V[i] + beta * sum(V[j] for j in nb[i])
    V2 = np.vstack([oldV, np.array(newV)])
    F2 = []
    for a, b, c in F:
        ab, bc, ca = eidx[ekey(a, b)], eidx[ekey(b, c)], eidx[ekey(c, a)]
        F2 += [[a, ab, ca], [ab, b, bc], [ca, bc, c], [ab, bc, ca]]
    return V2, np.array(F2)


for _ in range(2): V, F = loop(V, F)

x, y, z = V[:, 0], V[:, 1], V[:, 2]
sm = lambda e: np.clip(e, 0, 1) ** 2 * (3 - 2 * np.clip(e, 0, 1))
def ell(cx, cy, rx, ry, soft=0.35):
    d = np.sqrt(((x - cx) / rx) ** 2 + ((y - cy) / ry) ** 2)
    return sm((1 - d) / soft)
# the lips: between the upper lip's edge (y ≈ −3.4 at the middle) and the lower lip's (y ≈ −5.37), corners at x ±2.46
lips = ell(0, -4.38, 2.55, 1.02, 0.25) * sm((z - 4.1) / 0.5)
blush = np.maximum(ell(-4.4, -1.2, 2.1, 1.6, 0.9), ell(4.4, -1.2, 2.1, 1.6, 0.9))
shadow = np.maximum(ell(-3.15, 3.25, 1.75, 0.62, 0.7), ell(3.15, 3.25, 1.75, 0.62, 0.7))
# the contour: two soft bands down the sides of the nose (from between the brows to the nostril wings)
band = sm((1 - np.abs(np.abs(x) - 1.3) / 0.8) / 0.9) * sm((2.6 - y) / 1.0) * sm((y + 0.8) / 1.0)
contour = band
eyes = np.maximum(ell(-3.1, 2.75, 2.75, 1.9, 0.45), ell(3.1, 2.75, 2.75, 1.9, 0.45))
eyes = np.maximum(eyes, ell(0, 3.0, 1.6, 1.5, 0.5))

# the mask: a fabric surface stretched from the nose bridge over the nose tip down to the chin and out to the cheeks.
top = 1.6 - 0.16 * x ** 2                                   # its top edge: high over the nose, lower at the cheeks
inM = (y < top + 0.9) & (y > -9.6) & (np.abs(x) < 7.6)
def fabric(xx, yy):
    ridge = np.interp(yy, [-9.6, -6.5, -3.5, -0.5, 1.6], [4.7, 6.0, 6.95, 7.75, 6.7])   # the line over the nose tip and the chin
    return ridge - 0.115 * xx ** 2 - 0.0035 * xx ** 4
mz = np.where(inM, np.maximum(z + 0.18, fabric(x, y)), z)
fM = [f for f in F if inM[f].all()]
mvi = sorted(set(i for f in fM for i in f)); remap = {v: i for i, v in enumerate(mvi)}
MV = np.stack([x[mvi], y[mvi], mz[mvi]], 1); MF = [[remap[a], remap[b], remap[c]] for a, b, c in fM]
edgeM = top[mvi] - y[mvi]                                      # signed distance below the top edge (cm): < 0 is cut away per pixel

r3 = lambda a: [round(float(v), 3) for v in np.asarray(a).ravel()]
out = {
    "v": r3(V), "f": [int(i) for i in F.ravel()],
    "lips": r3(lips), "blush": r3(blush), "shadow": r3(shadow), "contour": r3(contour), "eyes": r3(eyes),
    "mv": r3(MV), "mf": [int(i) for t in MF for i in t], "mhem": r3(edgeM),
}
(ROOT / "assets/mesh/face.js").write_text("// generated by tools/mesh.py from MediaPipe's canonical face model (Apache-2.0)\nwindow.FACE = " + json.dumps(out, separators=(",", ":")) + ";\n")
print(len(V), "verts", len(F), "tris; mask", len(MV), "verts", len(MF), "tris;", (ROOT / "assets/mesh/face.js").stat().st_size // 1024, "KB")
