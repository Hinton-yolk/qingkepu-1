# model.py — turns outlines.json (traced from the user's four reference images) into assets/people/model.js,
# the arm and hand model the film draws (no photo is shown):
#   TUBE  the forearm as a tube: per world x (mm) the centre and half-width across (top image) and up/down (side image)
#   HANDS outlines, creases and nails in image px (the film maps them into the world)
#   MORPH the side arm, fist ↔ open: both outlines cut at the wrist and resampled to the same point count
import json, numpy as np
from PIL import Image
O = json.load(open("assets/people/outlines.json"))
TOP = dict(s=4.37, u0=1150, v0=370)
SIDE = dict(s=4.1, w0=np.array([1040.0, 541.0]), d=np.array([0.956, -0.296]))
N_ = np.array([SIDE["d"][1], -SIDE["d"][0]])                       # "up" in the side image
def alpha(f): return np.array(Image.open(f"assets/people/{f}"))[:, :, 3] > 128
At, As = alpha("arm-top.webp"), alpha("arm-side-fist.webp")
tube = []
for x in range(-285, 16, 5):
    u = TOP["u0"] + (x + 6) * TOP["s"]; ui = int(round(min(max(u, 0), At.shape[1] - 1)))
    ys = np.where(At[:, ui])[0]; yc = ((ys[0] + ys[-1]) / 2 - TOP["v0"]) / TOP["s"]; ry = (ys[-1] - ys[0]) / 2 / TOP["s"]
    p = SIDE["w0"] + SIDE["d"] * (x + 6) * SIDE["s"]
    def run(sg):
        for k in range(0, 400):
            q = p + sg * N_ * k; qi = (int(round(q[1])), int(round(q[0])))
            if not (0 <= qi[0] < As.shape[0] and 0 <= qi[1] < As.shape[1]) or not As[qi]: return k
        return 400
    up, dn = run(1), run(-1)
    zc = (up - dn) / 2 / SIDE["s"]; rz = (up + dn) / 2 / SIDE["s"]
    tube.append([x, round(yc, 2), round(ry, 2), round(zc, 2), round(rz, 2)])
# towards the elbow the side image turns into the upper arm: there the thickness follows the width (forearm ≈ 0.78 as thick as wide)
T = np.array(tube, float)
for i in range(len(T)):
    if T[i, 0] < -125: T[i, 3] = T[T[:, 0] == -125][0, 3]; T[i, 4] = 0.78 * T[i, 2]
# smooth
for c in (1, 2, 3, 4):
    v = T[:, c].copy(); T[:, c] = np.convolve(np.pad(v, 3, mode="edge"), np.ones(7) / 7, mode="valid")
tube = T.round(2).tolist()

def resample(P, n):
    P = np.asarray(P, float); d = np.r_[0, np.cumsum(np.hypot(*np.diff(P, axis=0).T))]
    s = np.linspace(0, d[-1], n); return np.c_[np.interp(s, d, P[:, 0]), np.interp(s, d, P[:, 1])]
def split(pts, xcut=1060):
    P = np.asarray(pts, float); n = len(P)
    inside = P[:, 0] >= xcut
    i0 = [i for i in range(n) if not inside[i] and inside[(i + 1) % n]][0]   # entering the hand
    i1 = [i for i in range(n) if inside[i] and not inside[(i + 1) % n]][0]   # leaving it
    roll = lambda a, b: [P[k % n] for k in range(a, b + (n if b < a else 0) + 1)]
    hand, rest = roll(i0 + 1, i1), roll(i1 + 1, i0)
    # orient the hand segment from the top crossing to the bottom one
    if hand[0][1] > hand[-1][1]: hand, rest = hand[::-1], rest[::-1]
    return hand, rest
morph = {}
for k in ("open", "fist"):
    h, r = split(O[k]["pts"]); morph[k] = np.r_[resample(h, 160), resample(r, 200)].round(1).tolist()
# the two must run the same way round: hand top→bottom then the rest from bottom back to top
out = {"TUBE": tube, "TOPI": {k: float(v) for k, v in TOP.items()}, "SIDEI": {"s": SIDE["s"], "w0": SIDE["w0"].tolist(), "d": SIDE["d"].tolist()},
       "MORPH": morph}
for k in ("top", "open", "fist", "pinch"):
    out[k] = {"pts": O[k]["pts"], "creases": [c["pts"] for c in O[k]["creases"] if np.hypot(*np.diff(np.array(c["pts"]), axis=0).T).sum() > 30],
              "nails": O[k]["nails"], "sleeve": O[k].get("sleeve"), "w": O[k]["w"], "h": O[k]["h"]}
open("assets/people/model.js", "w").write("// generated by tools/model.py from the user's reference images (2026-11-14) — do not edit by hand\nwindow.ARM_MODEL = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("tube", len(tube), tube[0], tube[-1]); print("wrist", [t for t in tube if t[0] in (-20, -5, 0, 10)])
