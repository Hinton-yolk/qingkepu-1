# handmodel.py — the user's reference photos (2026-11-24): assets/people/hands-press.webp (the right thumb pressing,
# transparent background) and hands-lift.webp (the same, the right thumb lifted; a checkerboard baked into the picture, so
# the hands are cut out by skin colour). → assets/people/model.js: per hand the outline, creases and nails, in image px.
# The film draws the hands itself from these (no photo is shown), like EP.05's feet and EP.07 / EP.08's hands.
#   LH  the left hand (from hands-press)        RH  the right hand, thumb pressing        RHL  the right hand, thumb lifted
import json, sys, numpy as np
from PIL import Image, ImageDraw
from skimage import measure, morphology, filters
from scipy import ndimage

def load(src, by_skin=False):
    im = np.array(Image.open(src).convert("RGBA")).astype(float)
    R, G, B, A = [im[:, :, i] for i in range(4)]
    if by_skin:   # the checkerboard is grey (R ≈ G ≈ B); skin is warm
        m = ((R - B) > 22) & (R > 110)
        m = morphology.binary_opening(m, morphology.disk(2))
        m = ndimage.binary_fill_holes(morphology.binary_closing(m, morphology.disk(6)))
    else:
        m = A > 128
    return im, m

def trace(im, m, side):
    R, G, B = im[:, :, 0], im[:, :, 1], im[:, :, 2]
    L = (0.3 * R + 0.59 * G + 0.11 * B) / 255
    lab = measure.label(m)
    regs = [r for r in measure.regionprops(lab) if r.area > 20000]
    reg = min(regs, key=lambda r: r.centroid[1]) if side == "L" else max(regs, key=lambda r: r.centroid[1])
    mm = lab == reg.label
    c = max(measure.find_contours(np.pad(mm.astype(float), 2), 0.5), key=len)
    P = measure.approximate_polygon(c, 1.2); pts = [[round(float(x) - 2, 1), round(float(y) - 2, 1)] for y, x in P]
    # creases: dark ridges inside the hand (the few strongest, long ones)
    inner = morphology.binary_erosion(mm, morphology.disk(10))
    r = filters.sato(L, sigmas=[2, 3, 4], black_ridges=True); r[~inner] = 0
    thr = np.percentile(r[inner], 97.5)
    sk = morphology.skeletonize(morphology.remove_small_objects(r > thr, 60))
    cl = measure.label(sk, connectivity=2); creases = []
    for rg in measure.regionprops(cl):
        if rg.area < 35: continue
        ys, xs = rg.coords[:, 0], rg.coords[:, 1]
        d = np.array([xs - xs.mean(), ys - ys.mean()]); u, s_, vt = np.linalg.svd(d, full_matrices=False)
        o = np.argsort(u[:, 0] @ d); Q = measure.approximate_polygon(np.stack([ys[o], xs[o]], 1).astype(float), 2.0)
        creases.append([[float(x), float(y)] for y, x in Q])
    creases = [c_ for c_ in creases if np.hypot(*np.diff(np.array(c_), axis=0).T).sum() > 30]
    # nails: paler, pinker than skin, near the outline
    nm = mm & (B / np.maximum(R, 1) > 0.70) & (R > 200) & (G / np.maximum(R, 1) > 0.76)
    nm = morphology.remove_small_objects(morphology.binary_opening(nm, morphology.disk(3)), 250)
    nails = []
    for rg in measure.regionprops(measure.label(nm)):
        if not (300 < rg.area < 12000): continue
        cy, cx = rg.centroid; dmin = min(np.hypot(px - cx, py - cy) for px, py in pts)
        if dmin > 60: continue
        cc = max(measure.find_contours(np.pad(rg.image, 1).astype(float), 0.5), key=len); y0, x0 = rg.bbox[:2]
        Pn = np.array([[x + x0 - 1, y + y0 - 1] for y, x in cc], float); cen = Pn.mean(0); U, S, Vt = np.linalg.svd(Pn - cen, full_matrices=False)
        ang = float(np.arctan2(Vt[0, 1], Vt[0, 0])); pr = (Pn - cen) @ Vt.T
        nails.append([round(float(cen[0]), 1), round(float(cen[1]), 1), round(float(np.ptp(pr[:, 0]) / 2 * 0.92), 1), round(float(np.ptp(pr[:, 1]) / 2 * 0.92), 1), round(ang, 3)])
    return {"pts": pts, "creases": creases, "nailE": nails, "bbox": [int(v) for v in reg.bbox]}

imP, mP = load("assets/people/hands-press.webp")
imL, mL = load("assets/people/hands-lift.webp", by_skin=True)
out = {"w": int(imP.shape[1]), "h": int(imP.shape[0]), "LH": trace(imP, mP, "L"), "RH": trace(imP, mP, "R"), "RHL": trace(imL, mL, "R")}
vis = Image.new("RGBA", (imP.shape[1], imP.shape[0] * 2), (236, 235, 230, 255))
vis.alpha_composite(Image.open("assets/people/hands-press.webp").convert("RGBA"), (0, 0)); vis.paste(Image.open("assets/people/hands-lift.webp").convert("RGBA"), (0, imP.shape[0]))
dr = ImageDraw.Draw(vis)
for name, oy in [("LH", 0), ("RH", 0), ("RHL", imP.shape[0])]:
    h = out[name]
    dr.line([(x, y + oy) for x, y in h["pts"]] + [(h["pts"][0][0], h["pts"][0][1] + oy)], fill=(0, 160, 255, 255), width=3)
    for c_ in h["creases"]: dr.line([(x, y + oy) for x, y in c_], fill=(255, 0, 80, 255), width=3)
    for (x, y, ra, rb, an) in h["nailE"]: dr.ellipse([x - ra, y + oy - ra, x + ra, y + oy + ra], outline=(0, 200, 0, 255), width=3)
    print(name, len(h["pts"]), "pts,", len(h["creases"]), "creases,", len(h["nailE"]), "nails, bbox", h["bbox"])
vis.convert("RGB").save("qa/hands-trace.jpg", quality=80)
open("assets/people/model.js", "w").write("// generated by tools/handmodel.py from the user's reference photos (2026-11-24) — do not edit by hand\nwindow.HAND_MODEL = " + json.dumps(out, separators=(",", ":")) + ";\n")
