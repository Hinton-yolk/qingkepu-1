#!/usr/bin/env python3
"""照图画手：从用户给的参考图（assets/people/ref-hand.webp，透明底）量出手的轮廓和明暗分区，写成矢量形状 assets/people/hand.js。
片子里不贴照片，由 index.html 用这些形状平涂（肤色 #EBCBA5 / 阴影 #D6AD84 / 高光），和 EP.07、EP.08「照图自己画」同一做法。
  python3 tools/trace_hand.py
输出：outline（外轮廓）、shade（阴影区，两层）、light（高光区）、crease（指缝、指节的细线）、thumb（拇指尖）、tips（指尖）。坐标是原图像素。"""
import json, pathlib
import numpy as np
from PIL import Image
from scipy import ndimage as ndi
from skimage import measure, morphology

ROOT = pathlib.Path(__file__).resolve().parent.parent
im = np.asarray(Image.open(ROOT / "assets/people/ref-hand.webp").convert("RGBA")).astype(float) / 255
H, W = im.shape[:2]
alpha = ndi.gaussian_filter(im[..., 3], 1.5)
mask = alpha > 0.5
L = im[..., :3] @ np.array([0.3, 0.59, 0.11])

def polys(field, level, tol, min_len=40):
    out = []
    for c in measure.find_contours(field, level):
        if len(c) < min_len: continue
        p = measure.approximate_polygon(c, tol)
        out.append([[round(float(x), 1), round(float(y), 1)] for y, x in p])
    return out

outline = max(polys(alpha, 0.5, 1.2), key=len)
# tones: heavily smoothed luminance inside the hand, split by percentiles (shadow, deeper shadow, highlight)
Ls = ndi.gaussian_filter(np.where(mask, L, np.nan_to_num(L[mask].mean())), 7)
inner = ndi.binary_erosion(mask, iterations=6)
p = np.percentile(Ls[inner], [22, 8, 88])
def region(cond, sigma=3):
    f = ndi.gaussian_filter((cond & inner).astype(float), sigma)
    return polys(f, 0.5, 1.5, 30)
shade1, shade2, light = region(Ls < p[0]), region(Ls < p[1]), region(Ls > p[2])
# creases: thin dark lines (local darkness much stronger than the surroundings), skeletonised into polylines
dark = (ndi.gaussian_filter(L, 6) - ndi.gaussian_filter(L, 1.2)) > 0.035
dark &= ndi.binary_erosion(mask, iterations=10)
dark = morphology.remove_small_objects(dark, 120)
crease = [q for q in polys(ndi.gaussian_filter(dark.astype(float), 1.5), 0.5, 1.5, 50)]
ys, xs = np.nonzero(mask)
thumb = [float(xs.min()), float(ys[xs == xs.min()].mean())]
tips_y = ys.max(); tips = [float(xs[ys == tips_y].mean()), float(tips_y)]
data = {"w": W, "h": H, "outline": outline, "shade1": shade1, "shade2": shade2, "light": light, "crease": crease, "thumb": thumb, "tips": tips}
(ROOT / "assets/people/hand.js").write_text("// generated by tools/trace_hand.py from assets/people/ref-hand.webp — do not edit\nwindow.HAND = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
print("outline", len(outline), "pts; shade", len(shade1), len(shade2), "light", len(light), "crease", len(crease), "thumb", thumb, "tips", tips)
