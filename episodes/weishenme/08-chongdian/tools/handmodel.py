# handmodel.py — the user's reference photo (2026-11-17, assets/people/hands-pinch.webp: a left and a right hand pinching)
# → assets/people/model.js: per hand the outline, creases and nails (as ellipses), in image px. The film draws the hands
# itself from these (no photo is shown), like EP.05's feet and EP.07's arm.
import json, numpy as np
from PIL import Image, ImageDraw
from skimage import measure, morphology, filters
src = "assets/people/hands-pinch.webp"
im = np.array(Image.open(src)).astype(float); R, G, B, A = [im[:, :, i] for i in range(4)]
a = A / 255; L = (0.3 * R + 0.59 * G + 0.11 * B) / 255
lab = measure.label(a > 0.5)
regs = sorted([r for r in measure.regionprops(lab) if r.area > 20000], key=lambda r: r.centroid[1])
out = {"w": im.shape[1], "h": im.shape[0]}
vis = Image.new("RGBA", (im.shape[1], im.shape[0]), (236, 235, 230, 255)); vis.alpha_composite(Image.open(src).convert("RGBA")); dr = ImageDraw.Draw(vis)
for name, reg in zip(["LH", "RH"], regs):
    m = lab == reg.label
    c = max(measure.find_contours(np.pad(m.astype(float), 2), 0.5), key=len)
    P = measure.approximate_polygon(c, 1.2); pts = [[round(float(x) - 2, 1), round(float(y) - 2, 1)] for y, x in P]
    # creases: dark ridges inside the hand
    inner = morphology.binary_erosion(m, morphology.disk(9))
    r = filters.sato(L, sigmas=[2, 3, 4], black_ridges=True); r[~inner] = 0
    thr = np.percentile(r[inner], 97.0)
    sk = morphology.skeletonize(morphology.remove_small_objects(r > thr, 50))
    cl = measure.label(sk, connectivity=2); creases = []
    for rg in measure.regionprops(cl):
        if rg.area < 30: continue
        ys, xs = rg.coords[:, 0], rg.coords[:, 1]
        d = np.array([xs - xs.mean(), ys - ys.mean()]); u, s_, vt = np.linalg.svd(d, full_matrices=False)
        o = np.argsort(u[:, 0] @ d); Q = measure.approximate_polygon(np.stack([ys[o], xs[o]], 1).astype(float), 2.0)
        creases.append([[float(x), float(y)] for y, x in Q])
    # nails: pinker, bluer than skin, near the outline
    nm = m & (B / np.maximum(R, 1) > 0.66) & (R > 195) & (G / np.maximum(R, 1) > 0.72)
    nm = morphology.remove_small_objects(morphology.binary_opening(nm, morphology.disk(3)), 250)
    nails = []
    for rg in measure.regionprops(measure.label(nm)):
        if not (300 < rg.area < 9000): continue
        cy, cx = rg.centroid; dmin = min(np.hypot(px - cx, py - cy) for px, py in pts)
        if dmin > 45: continue
        cc = max(measure.find_contours(np.pad(rg.image, 1).astype(float), 0.5), key=len); y0, x0 = rg.bbox[:2]
        Pn = np.array([[x + x0 - 1, y + y0 - 1] for y, x in cc], float); cen = Pn.mean(0); U, S, Vt = np.linalg.svd(Pn - cen, full_matrices=False)
        ang = float(np.arctan2(Vt[0, 1], Vt[0, 0])); pr = (Pn - cen) @ Vt.T
        nails.append([round(float(cen[0]), 1), round(float(cen[1]), 1), round(float(np.ptp(pr[:, 0]) / 2 * 0.92), 1), round(float(np.ptp(pr[:, 1]) / 2 * 0.92), 1), round(ang, 3)])
    out[name] = {"pts": pts, "creases": [c_ for c_ in creases if np.hypot(*np.diff(np.array(c_), axis=0).T).sum() > 28], "nailE": nails, "bbox": [int(v) for v in reg.bbox]}
    dr.line([tuple(p) for p in pts] + [tuple(pts[0])], fill=(0, 160, 255, 255), width=3)
    for c_ in out[name]["creases"]: dr.line([tuple(p) for p in c_], fill=(255, 0, 80, 255), width=3)
    for (x, y, ra, rb, an) in nails: dr.ellipse([x - ra, y - ra, x + ra, y + ra], outline=(0, 200, 0, 255), width=3)
    print(name, len(pts), "pts,", len(out[name]["creases"]), "creases,", len(nails), "nails, bbox", reg.bbox)
vis.convert("RGB").save("qa/hands-trace.jpg", quality=80)
open("assets/people/model.js", "w").write("// generated by tools/handmodel.py from the user's reference photo (2026-11-17) — do not edit by hand\nwindow.HAND_MODEL = " + json.dumps(out, separators=(",", ":")) + ";\n")
