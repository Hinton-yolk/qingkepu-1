def subs(s):
    # 按标点切；相邻几段合起来不超过 19 字就并成一条（并的时候保留原来的标点，字幕要能在原句里找到）
    parts = [p for p in re.split(r'(?<=[，：；。？、！])', s) if p.strip()]; out = []
    for p in parts:
        p = p.strip(); core = p.rstrip('，；。、：')
        if out and not out[-1][1].endswith('？') and len(out[-1][1]) + len(core) <= 19: out[-1] = (out[-1][0] + p, out[-1][0] + core)
        else: out.append((p, core))
    return [c for _, c in out]
